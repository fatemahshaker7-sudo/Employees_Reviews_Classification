import pandas as pd
from transformers import pipeline
from sklearn.metrics import accuracy_score, f1_score, ConfusionMatrixDisplay
import matplotlib.pyplot as plt

# create the sample file
df = pd.read_csv("employee_reviews.csv", encoding="latin-1").sample(100, random_state=42)
df["text"] = df[["summary", "pros", "cons"]].fillna("").agg(" ".join, axis=1)
df["label"] = df["overall-ratings"].map({1: "neg", 2: "neg", 3: "neu", 4: "pos", 5: "pos"})
df["classes"] = ""
df[["text","overall-ratings", "label", "cons", "classes" ]].to_csv("sample_100.csv", index=False)

# Load it
df = pd.read_csv("sample_100.csv")
texts, ratings, labels, cons, classes = (df[c].tolist() for c in ["text", "overall-ratings", "label", "cons", "classes"])

models = ["cardiffnlp/twitter-roberta-base-sentiment-latest",
    "lxyuan/distilbert-base-multilingual-cased-sentiments-student",
    "finiteautomata/bertweet-base-sentiment-analysis",]

for model in models:
    clf = pipeline("sentiment-analysis", model=model, truncation=True)
    preds = [o["label"][:3].lower() for o in clf(texts)]   # positive/POS -> "pos"
    print(model)
    # metrics
    print("  Accuracy:", round(accuracy_score(labels, preds), 3))
    print("  F1:      ", round(f1_score(labels, preds, average="macro"), 3))
    # Confusion matrix
    ConfusionMatrixDisplay.from_predictions(labels, preds, labels=["neg", "neu", "pos"], cmap="Blues")
    plt.title(model)
    plt.show()

# Incorrect predictions (first 100)
for text, true, pred in zip(texts, labels, preds):
    if true != pred:
        print(text[:80], "| true:", true, "| predicted:", pred)

df = pd.read_csv("sample_100.csv").dropna(subset=["classes", "cons"])
issues = ["management", "pay", "work-life balance", "career growth", "culture"]
clf = pipeline("zero-shot-classification", model="typeform/distilbert-base-uncased-mnli")

true = df["classes"].tolist()
preds = [clf(t, candidate_labels=issues)["labels"][0] for t in df["cons"]]

print("Accuracy:", round(accuracy_score(true, preds), 3))
print("Macro F1:", round(f1_score(true, preds, average="macro"), 3))
ConfusionMatrixDisplay.from_predictions(true, preds, labels=issues, xticks_rotation=45);

